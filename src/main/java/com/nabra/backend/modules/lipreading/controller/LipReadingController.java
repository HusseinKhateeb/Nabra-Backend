  @PostMapping(value = "/avsr/upload-audio", consumes = MediaType.MULTIPART_FORM_DATA_VALUE)
  public ResponseEntity<String> uploadAudio(
      @RequestParam("audioFile") MultipartFile audioFile) throws Exception {
    // SecurityUtils.currentPrincipal(); // ensure authenticated
    log.info("Received audio upload request");

    if (audioFile == null || audioFile.isEmpty()) {
      throw new IllegalArgumentException("audioFile is required");
    }

    Path audioTemp = null;
    try {
      audioTemp = Files.createTempFile("avsr-audio-", extensionOf(audioFile.getOriginalFilename()));
      audioFile.transferTo(audioTemp);

      // Use persistent audio worker for fast inference
      String result = invokeAudioWorker(audioTemp);
      // Return JSON object with 'result' field
      String json = OBJECT_MAPPER.writeValueAsString(Map.of("result", result));
      return ResponseEntity.ok()
          .contentType(MediaType.APPLICATION_JSON)
          .body(json);
    } finally {
      deleteQuietly(audioTemp);
    }
  }

  // Persistent audio worker invocation
  private String invokeAudioWorker(Path audioTemp) throws Exception {
    synchronized (audioWorkerLock) {
      IOException lastError = null;
      for (int attempt = 0; attempt < 2; attempt++) {
        ensureAudioWorkerStarted();
        Map<String, Object> request = new LinkedHashMap<>();
        request.put("audioPath", audioTemp.toAbsolutePath().toString());
        audioWorkerStdin.write(OBJECT_MAPPER.writeValueAsString(request));
        audioWorkerStdin.newLine();
        audioWorkerStdin.flush();
        String responseLine = readLineWithTimeout(audioWorkerStdout, audioWorkerProcess, 120);
        if (responseLine == null) {
          stopAudioWorker();
          lastError = new IOException("Audio worker closed stdout unexpectedly");
          log.warn("Audio worker died on attempt {}, restarting...", attempt + 1);
          continue;
        }
        JsonNode response = OBJECT_MAPPER.readTree(responseLine);
        if (!response.has("result")) {
          throw new IOException("Audio worker did not return a 'result' field: " + responseLine);
        }
        return response.path("result").asText("");
      }
      throw lastError;
    }
  }

  private void ensureAudioWorkerStarted() throws IOException {
    if (audioWorkerProcess != null && audioWorkerProcess.isAlive() && audioWorkerStdin != null && audioWorkerStdout != null) {
      return;
    }
    stopAudioWorker();
    String pythonExe = resolveWhisperPythonExecutable();
    ProcessBuilder workerPb = new ProcessBuilder(pythonExe, AUDIO_WORKER_SCRIPT);
    workerPb.directory(new File(AUDIO_WORK_DIR));
    workerPb.redirectErrorStream(false);
    Process process = workerPb.start();
    java.io.BufferedWriter stdin = new java.io.BufferedWriter(
        new java.io.OutputStreamWriter(process.getOutputStream(), java.nio.charset.StandardCharsets.UTF_8));
    java.io.BufferedReader stdout = new java.io.BufferedReader(
        new java.io.InputStreamReader(process.getInputStream(), java.nio.charset.StandardCharsets.UTF_8));
    java.io.BufferedReader stderr = new java.io.BufferedReader(
        new java.io.InputStreamReader(process.getErrorStream(), java.nio.charset.StandardCharsets.UTF_8));
    Thread stderrDrainer = new Thread(() -> {
      try {
        String line;
        while ((line = stderr.readLine()) != null) {
          log.debug("[audio-worker] {}", line);
        }
      } catch (IOException ignored) {}
    }, "audio-worker-stderr");
    stderrDrainer.setDaemon(true);
    stderrDrainer.start();
    audioWorkerProcess = process;
    audioWorkerStdin = stdin;
    audioWorkerStdout = stdout;
  }

  private String resolveWhisperPythonExecutable() {
    String[] candidates = {
        System.getenv("AVSR_WHISPER_PYTHON"),
        System.getenv("AVSR_ASR_PYTHON"),
        "python",
        "python3",
        "py"
    };

    for (String candidate : candidates) {
      if (candidate == null || candidate.isBlank()) {
        continue;
      }
      if (canImportWhisper(candidate)) {
        return candidate;
      }
    }

    log.warn("No Python interpreter with Whisper was found; falling back to 'python'. Set AVSR_WHISPER_PYTHON to a working interpreter.");
    return "python";
  }

  private boolean canImportWhisper(String pythonExe) {
    Process process = null;
    try {
      ProcessBuilder processBuilder = new ProcessBuilder(pythonExe, "-c", "import whisper");
      processBuilder.redirectErrorStream(true);
      process = processBuilder.start();
      if (!process.waitFor(10, TimeUnit.SECONDS)) {
        process.destroyForcibly();
        return false;
      }
      return process.exitValue() == 0;
    } catch (Exception ex) {
      return false;
    } finally {
      if (process != null) {
        process.destroy();
      }
    }
  }

  private void stopAudioWorker() {
    synchronized (audioWorkerLock) {
      if (audioWorkerStdin != null) {
        try { audioWorkerStdin.close(); } catch (IOException ignored) {}
      }
      if (audioWorkerStdout != null) {
        try { audioWorkerStdout.close(); } catch (IOException ignored) {}
      }
      if (audioWorkerProcess != null) {
        if (audioWorkerProcess.isAlive()) {
          audioWorkerProcess.destroy();
          try {
            if (!audioWorkerProcess.waitFor(3, TimeUnit.SECONDS)) {
              audioWorkerProcess.destroyForcibly();
              audioWorkerProcess.waitFor(2, TimeUnit.SECONDS);
            }
          } catch (InterruptedException ignored) {
            audioWorkerProcess.destroyForcibly();
          }
        }
      }
      audioWorkerStdin = null;
      audioWorkerStdout = null;
      audioWorkerProcess = null;
    }
  }
  

