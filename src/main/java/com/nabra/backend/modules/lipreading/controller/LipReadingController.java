  private String readLineWithTimeout(java.io.BufferedReader reader, Process process, long timeoutSecs) throws IOException {
    Thread killer = new Thread(() -> {
      try {
        Thread.sleep(timeoutSecs * 1000);
        if (process.isAlive()) {
          process.destroyForcibly();
        }
      } catch (InterruptedException ignored) {}
    }, "worker-killer");
    killer.setDaemon(true);
    killer.start();
    try {
      return reader.readLine();
    } finally {
      killer.interrupt();
    }
  }

  private void deleteQuietly(Path path) {
    if (path == null) {
      return;
    }
    try {
      Files.deleteIfExists(path);
    } catch (Exception ignored) {
    }
  }

  private String extensionOf(String fileName) {
    if (fileName == null) {
      return ".tmp";
    }
    String normalized = fileName.trim().toLowerCase(Locale.ROOT);
    int dot = normalized.lastIndexOf('.');
    if (dot <= -1 || dot == normalized.length() - 1) {
      return ".tmp";
    }
    return normalized.substring(dot);
  }

  private void persistFusionSession(FusionJob job, Exception ex) {
    if (job == null || job.userId == null || job.userId.isBlank()) {
      return;
    }
    if (STATUS_COMPLETED.equals(job.status)) {
      String resultText = extractFusionResultText(job.parsedResult);
      if (resultText == null && job.rawOutput != null) {
        resultText = job.rawOutput.trim();
      }
      Double accuracyScore = extractFusionConfidence(job.parsedResult);
      String content = buildAvsrHistoryContent(job, ex);
      saveCompletedSession(
          job.userId,
          SessionInputType.RECORDED,
          SessionOutputType.TEXT,
          resultText,
          null,
          accuracyScore,
          content
      );
      return;
    }

    String error = ex != null ? ex.getMessage() : job.error;
    String content = buildAvsrHistoryContent(job, ex);
    saveFailedSession(
        job.userId,
        SessionInputType.RECORDED,
        SessionOutputType.TEXT,
        error,
        content
    );
  }

  private Double extractFusionConfidence(JsonNode parsedResult) {
    if (parsedResult == null) {
      return null;
    }

    JsonNode fused = parsedResult.get("fused_conf");
    if (fused != null && fused.isNumber()) {
      return fused.asDouble();
    }

    JsonNode lip = parsedResult.get("lip_conf");
    if (lip != null && lip.isNumber()) {
      return lip.asDouble();
    }

    return null;
  }

  private String buildAvsrHistoryContent(FusionJob job, Exception ex) {
    Map<String, Object> payload = new LinkedHashMap<>();
    payload.put("source", "avsr");
    payload.put("status", job == null ? null : job.status);

    if (job != null && job.parsedResult != null) {
      payload.put("result", job.parsedResult);
    } else if (job != null && job.rawOutput != null && !job.rawOutput.isBlank()) {
      payload.put("rawOutput", job.rawOutput.trim());
    }

    String error = ex != null ? ex.getMessage() : (job == null ? null : job.error);
    if (error != null && !error.isBlank()) {
      payload.put("error", error);
    }

    return jsonToCompactString(OBJECT_MAPPER.valueToTree(payload));
  }

  private String extractFusionResultText(JsonNode parsedResult) {
    if (parsedResult == null) {
      return null;
    }

    String[] preferredFields = {
        "finalWord",
        "final_word",
        "matchedLipWord",
        "matched_lip_word",
        "audioText",
        "audio_text",
        "recognizedText",
        "recognized_text"
    };

    for (String field : preferredFields) {
      JsonNode node = parsedResult.get(field);
      if (node != null && !node.isNull() && !node.asText("").isBlank()) {
        return node.asText();
      }
    }

    return jsonToCompactString(parsedResult);
  }

  private String jsonToCompactString(JsonNode node) {
    try {
      return OBJECT_MAPPER.writeValueAsString(node);
    } catch (Exception ignored) {
      return node == null ? null : node.toString();
    }
  }

  private void saveCompletedSession(
      String userId,
      SessionInputType inputType,
      SessionOutputType outputType,
      String resultText,
      String resultAudioUrl,
      Double accuracyScore,
      String content
  ) {
    try {
      sessionService.recordCompleted(userId, inputType, outputType, resultText, resultAudioUrl, accuracyScore, content);
    } catch (Exception saveEx) {
      log.warn("Failed to persist completed session history", saveEx);
    }
  }

  private void saveFailedSession(
      String userId,
      SessionInputType inputType,
      SessionOutputType outputType,
      String errorText,
      String content
  ) {
    try {
      sessionService.recordFailed(userId, inputType, outputType, errorText, content);
    } catch (Exception saveEx) {
      log.warn("Failed to persist failed session history", saveEx);
    }
  }
